// Helper function to get the right icon based on db type code/name
export const getDatabaseIcon = (dbTypeName, className = "w-5 h-5") => {
  const name = (dbTypeName || '').toLowerCase();
  
  if (name.includes('mssql') || name.includes('sql server') || name.includes('microsoft')) {
    return <MsSqlIcon className={className} />;
  }
  if (name.includes('mysql')) {
    return <MySqlIcon className={className} />;
  }
  if (name.includes('postgres') || name.includes('postgresql')) {
    return <PostgreSqlIcon className={className} />;
  }
  if (name.includes('oracle')) {
    return <OracleIcon className={className} />;
  }
  if (name.includes('sqlite')) {
    return <SqliteIcon className={className} />;
  }
  if (name.includes('maria')) {
    return <MariaDbIcon className={className} />;
  }
  if (name.includes('mongo')) {
    return <MongoDbIcon className={className} />;
  }
  
  return <GenericDbIcon className={className} />;
};
